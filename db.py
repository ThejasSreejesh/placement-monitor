"""
Local durable backend — SQLite.

Stores the data that must NEVER be lost across code changes, restarts, crashes
or rescans: which offers you've applied to, and your "last seen" marker.
SQLite gives ACID transactions + atomic writes (WAL mode), so a mid-write crash
can't corrupt or wipe your data. Offer data itself stays in offers.json (it's
regenerated by scans and safe to rebuild).
"""
import os
import sqlite3
import threading
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(HERE, "placement.db")
_lock = threading.Lock()


def _conn():
    c = sqlite3.connect(DB_PATH, timeout=15)
    c.execute("PRAGMA journal_mode=WAL")      # durable + concurrent reads
    c.execute("PRAGMA synchronous=NORMAL")
    return c


def init():
    with _conn() as c:
        c.execute("""CREATE TABLE IF NOT EXISTS applied(
                       oid TEXT PRIMARY KEY,
                       applied INTEGER NOT NULL DEFAULT 1,
                       date TEXT)""")
        c.execute("""CREATE TABLE IF NOT EXISTS meta(
                       key TEXT PRIMARY KEY, value TEXT)""")
        c.execute("""CREATE TABLE IF NOT EXISTS seen_offers(
                       oid TEXT PRIMARY KEY)""")


def get_seen_offers():
    with _conn() as c:
        rows = c.execute("SELECT oid FROM seen_offers").fetchall()
    return {r[0] for r in rows}


def mark_seen_offer(oid, seen=True):
    with _lock, _conn() as c:
        if seen:
            c.execute("INSERT OR IGNORE INTO seen_offers(oid) VALUES(?)", (oid,))
        else:
            c.execute("DELETE FROM seen_offers WHERE oid=?", (oid,))


def mark_seen_offers(oids):
    with _lock, _conn() as c:
        c.executemany("INSERT OR IGNORE INTO seen_offers(oid) VALUES(?)",
                      [(o,) for o in oids])


def get_applied():
    with _conn() as c:
        rows = c.execute(
            "SELECT oid, applied, date FROM applied WHERE applied=1").fetchall()
    return {r[0]: {"applied": bool(r[1]), "date": r[2] or ""} for r in rows}


def set_applied(oid, want):
    """Mark/unmark an offer applied. Returns the new total applied count."""
    with _lock, _conn() as c:
        if want:
            row = c.execute("SELECT date FROM applied WHERE oid=?", (oid,)).fetchone()
            d = (row[0] if row and row[0] else date.today().isoformat())
            c.execute("""INSERT INTO applied(oid, applied, date) VALUES(?,1,?)
                         ON CONFLICT(oid) DO UPDATE SET applied=1, date=excluded.date""",
                      (oid, d))
        else:
            c.execute("DELETE FROM applied WHERE oid=?", (oid,))
        total = c.execute("SELECT COUNT(*) FROM applied WHERE applied=1").fetchone()[0]
    return total


def applied_series():
    with _conn() as c:
        rows = c.execute(
            """SELECT date, COUNT(*) FROM applied
               WHERE applied=1 AND date IS NOT NULL AND date<>''
               GROUP BY date ORDER BY date""").fetchall()
    return [{"date": r[0], "count": r[1]} for r in rows]


def get_meta(key, default=None):
    with _conn() as c:
        row = c.execute("SELECT value FROM meta WHERE key=?", (key,)).fetchone()
    return row[0] if row else default


def set_meta(key, value):
    with _lock, _conn() as c:
        c.execute("""INSERT INTO meta(key, value) VALUES(?,?)
                     ON CONFLICT(key) DO UPDATE SET value=excluded.value""",
                  (key, str(value)))


def migrate_from_json(applied_json=None, seen_last_id=None):
    """One-time import of legacy JSON files, so nothing is lost in the switch."""
    with _conn() as c:
        empty = c.execute("SELECT COUNT(*) FROM applied").fetchone()[0] == 0
    if empty and applied_json:
        with _lock, _conn() as c:
            for oid, rec in applied_json.items():
                if isinstance(rec, dict) and rec.get("applied"):
                    c.execute("INSERT OR REPLACE INTO applied(oid, applied, date) "
                              "VALUES(?,1,?)", (oid, rec.get("date")))
    if get_meta("last_seen_id") is None and seen_last_id is not None:
        set_meta("last_seen_id", int(seen_last_id))
